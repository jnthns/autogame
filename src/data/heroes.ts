import type { ClassName } from './classes';
import type { TraitName } from './traits';

export type AttackStyle = 'melee' | 'ranged';

export interface HeroDef {
  id: string;
  name: string;
  origin: string;
  creature: string;
  cost: number;
  glyph: string;
  heroClass: ClassName;
  traits: TraitName[];
  hp: number;
  dmg: number;
  as: number;
  /** melee = adjacent only; ranged = cannot close — attacks at `range` tiles. */
  attack: AttackStyle;
  range: number;
  /** Supports deal no direct damage with their cast; used by the stat budget. */
  abilityKind?: 'damage' | 'support';
  crit: number;
  ability: string;
  abilityText: string;
  lore: string;
  quirk: string;
}

export function isMeleeHero(h: HeroDef): boolean {
  return h.attack === 'melee';
}

export function attackLabel(h: HeroDef): string {
  return h.attack === 'melee' ? 'Melee' : `Range ${h.range}`;
}

