const cache: Record<string, string> = {};

export function spriteCss(id: string): string {
  const s = SPRITES[id];
  if (!s) return '';
  if (cache[id]) return cache[id];

  const size = s.d.length;
  const cv = document.createElement('canvas');
  cv.width = size;
  cv.height = size;
  const cx = cv.getContext('2d');
  if (!cx) return '';

  s.d.forEach((row, y) => {
    for (let x = 0; x < size; x++) {
      const ch = row[x];
      if (!ch || ch === '.') continue;
      const col = s.p[ch];
      if (!col) continue;
      cx.fillStyle = col;
      cx.fillRect(x, y, 1, 1);
    }
  });

  cache[id] = cv.toDataURL();
  return cache[id];
}
